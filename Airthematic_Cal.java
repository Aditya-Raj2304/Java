class Airthematic_Cal {
    public static void main(String arg[]) {
        int x, y;
        x = 26;
        y = 4;
        int a = x + y;
        int b = x - y;
        int c = x / y;
        int d = x % y;
        int e = x * y;

        System.out.println("x + y = " + a);
        System.out.println("x - y = " + b);
        System.out.println("x / y = " + c);
        System.out.println("x % y = " + d);
        System.out.println("x * y = " + e);
    }
}